// width of a string at a given height, matching what text() will use
Pen.prototype.textWidth = function (str, size, spacing) {
  const u = size / 6, sp = spacing == null ? 1 : spacing;
  let w = 0;
  for (const ch of str.toUpperCase()) w += ((GW[ch] == null ? 4 : GW[ch]) + 1.5 * sp) * u;
  return w - 1.5 * sp * u;
};

// x,y is the top left of the first letter. o: slant, rot (radians about x,y), spacing, wob, p, speed
Pen.prototype.text = function (str, x, y, size, o) {
  o = o || {}; const rng = this.rng, u = size / 6, sl = o.slant == null ? 0.14 : o.slant, sp = o.spacing == null ? 1 : o.spacing;
  const cr = Math.cos(o.rot || 0), sr = Math.sin(o.rot || 0);
  let cx = 0;
  const to = (px, py) => [x + px * cr - py * sr, y + px * sr + py * cr];
  for (const ch of str.toUpperCase()) {
    const w = GW[ch] == null ? 4 : GW[ch], g = GL[ch];
    if (g) {
      const k = 0.94 + rng() * 0.12, jy = (rng() - 0.5) * size * 0.06, jr = (rng() - 0.5) * 0.05;
      for (const st of g) {
        const pts = st.map(q => {
          let gx = q[0] * k, gy = q[1] * k;
          gx += (gy - 3) * jr * 1.2 + (6 - gy) * sl;
          return to(cx + gx * u, jy + gy * u);
        });
        this.trace(pts, { speed: o.speed == null ? 0.4 : o.speed, p: o.p == null ? 0.82 : o.p, wob: o.wob == null ? 0.22 : o.wob, head: 1.5, tail: 3, blob: 0.3, free: o.free });
      }
    }
    cx += (w + 1.5 * sp) * u;
  }
};

